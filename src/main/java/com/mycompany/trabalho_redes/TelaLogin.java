    public static PublicKey carregarChavePublica(String caminho) throws Exception {
        String pem = Files.readString(Paths.get(caminho));

        pem = pem.replace("-----BEGIN PUBLIC KEY-----", "")
                .replace("-----END PUBLIC KEY-----", "")
                .replaceAll("\\s+", "");

        byte[] bytes = Base64.getDecoder().decode(pem);

        KeyFactory kf = KeyFactory.getInstance("RSA");

        return kf.generatePublic(new X509EncodedKeySpec(bytes));
    }

    private void CadastrarNomeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CadastrarNomeActionPerformed
        String ip = JOptionPane.showInputDialog(
                this,
                "Digite o IP do servidor:",
                "192.168.1.4"
        );

        if (ip == null || ip.trim().isEmpty()) {
            return; 
        }
        try {
            Socket socket = new Socket(ip, 9090);
            BufferedReader in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
            PrintWriter out = new PrintWriter(socket.getOutputStream(), true);
            String nome = CampoNome.getText();
            File cert = new File("src/main/java/certificados/" + nome + ".crt");
            byte[] bytes = Files.readAllBytes(cert.toPath());
            String certBase64 = Base64.getEncoder().encodeToString(bytes);
            out.println("LOGIN " + nome + " " + certBase64);
            boolean loginOk = false;
            boolean brokerValido = false;
            while (true) {
                String resposta = in.readLine();
                System.out.println("Servidor: " + resposta);
                if (resposta != null && resposta.contains("LOGIN OK")) {
                    loginOk = true;
                    out.println("VALID_BROKER " + nome);
                    resposta = in.readLine();
                    System.out.println("Servidor: " + resposta);
                    if (resposta.startsWith("BROKER_CERT ")) {
                        String brokerBase64 = resposta.substring("BROKER_CERT ".length());
                        byte[] certBytes = Base64.getDecoder().decode(brokerBase64);
                        brokerValido = validarBroker(certBytes);
                        if (loginOk && brokerValido) {
                            TelaPrincipal TelaPrincipal = new TelaPrincipal(socket, in, out, nome);
                            TelaPrincipal.setVisible(true);
                            this.dispose();
                            break;
                        }
                    }

                } else {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "Falha no Login: Certificado inválido ou não encontrado!",
                            "Erro de Autenticação",
                            javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (IOException ex) {
            Logger.getLogger(Cliente.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_CadastrarNomeActionPerformed

