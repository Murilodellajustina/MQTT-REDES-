    public boolean validarBroker(byte[] certBytes) {
        try {
            CertificateFactory cf = CertificateFactory.getInstance("X.509");

            X509Certificate certBroker = (X509Certificate) cf.generateCertificate(new ByteArrayInputStream(certBytes));

            PublicKey chaveAC = carregarChavePublica("C:\\Users\\MURILO\\OneDrive\\Desktop\\Fase 5\\redes 2\\Trabalho_Redes\\src\\main\\java\\keys\\AC_Pub.key");

            certBroker.verify(chaveAC);

            certBroker.checkValidity();

            return true;
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        }
    }

